import fs from 'node:fs';
import path from 'node:path';

// Keep the licenses of bundled renderer dependencies with source and desktop builds.
const root = path.resolve(import.meta.dirname, '..');
const bundled = ['react', 'react-dom', '@xyflow/react', 'three', 'lucide-react'];
const packages = new Map();

function findPackage(name, from) {
  let current = from;
  while (true) {
    const candidate = path.join(current, 'node_modules', name);
    if (fs.existsSync(path.join(candidate, 'package.json'))) return candidate;
    const parent = path.dirname(current);
    if (parent === current) throw new Error(`Cannot locate license for ${name}`);
    current = parent;
  }
}

function collect(name, from) {
  const folder = findPackage(name, from);
  const pkg = JSON.parse(fs.readFileSync(path.join(folder, 'package.json'), 'utf8'));
  const id = `${pkg.name}@${pkg.version}`;
  if (packages.has(id)) return;
  const files = fs.readdirSync(folder).filter(file => /^(licen[cs]e|copying|notice)([.-]|$)/i.test(file) && fs.statSync(path.join(folder, file)).isFile());
  if (!files.length) throw new Error(`Missing license text for ${id}`);
  packages.set(id, { pkg, texts: files.map(file => fs.readFileSync(path.join(folder, file), 'utf8').trim()) });
  for (const dependency of Object.keys(pkg.dependencies || {})) collect(dependency, folder);
}

for (const name of bundled) collect(name, root);
let output = 'Third-party licenses for the bundled Rig Studio renderer\n';
output += 'Generated by scripts/third-party-notices.mjs. Electron distributes separate Chromium notices.\n';
for (const [id, { pkg, texts }] of [...packages.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  output += `\n${'='.repeat(72)}\n${id} — ${pkg.license || 'See license below'}\n${'='.repeat(72)}\n\n${texts.join('\n\n')}\n`;
}
fs.writeFileSync(path.join(root, 'THIRD_PARTY_LICENSES.txt'), output);
console.log(`Collected license texts for ${packages.size} bundled dependencies.`);
